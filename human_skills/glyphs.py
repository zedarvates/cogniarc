# ─── Combined ────────────────────────────────────────────────────

GLYPHS: Dict[str, GlyphDef] = {**_DIGITS, **_LETTERS}


def get_glyph(char: str) -> GlyphDef:
    """Return the skeleton strokes for a character.

    Raises KeyError if char not found.
    """
    return GLYPHS[char.upper()]


def list_glyphs() -> List[str]:
    """Return all available glyph keys."""
    return list(GLYPHS.keys())
